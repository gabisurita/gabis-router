#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")"

if [ ! -f target/wasm-pkg/rsrouter_wasm_bg.wasm ]; then
  ./build.sh
fi

mkdir -p ../../shell/units/brouter

deno eval '
  import { gzip } from "node:zlib";
  import { promisify } from "node:util";
  const gz = promisify(gzip);

  const wasmBytes = await Deno.readFile("target/wasm-pkg/rsrouter_wasm_bg.wasm");
  const gzBytes = await gz(wasmBytes, { level: 9 });
  const b64 = gzBytes.toString("base64");

  const lookups = await Deno.readTextFile("profiles/lookups.dat");
  const profiles = {};
  for await (const entry of Deno.readDir("profiles")) {
    if (entry.isFile && entry.name.endsWith(".brf")) {
      const name = entry.name.replace(/\.brf$/, "");
      profiles[name] = await Deno.readTextFile(`profiles/${entry.name}`);
    }
  }

  const embeddedSegments = {};
  for await (const entry of Deno.readDir("segments")) {
    if (entry.isFile && entry.name.endsWith(".rd5")) {
      const name = entry.name.replace(/\.rd5$/, "");
      const segBytes = await Deno.readFile(`segments/${entry.name}`);
      const segGz = await gz(segBytes, { level: 9 });
      embeddedSegments[name] = segGz.toString("base64");
    }
  }

  let glue = await Deno.readTextFile("target/wasm-pkg/rsrouter_wasm.js");
  glue = glue
    .replace(/^export class WasmRouter/m, "class WasmRouter")
    .replace(/if \(module_or_path === undefined\) \{\s*module_or_path = new URL\([^)]+\);\s*\}/m, "")
    .replace(/^export \{ initSync, __wbg_init as default \};\s*$/m, "")
    .replace(/^\s*\/\/\s*TODO.*$/gm, "");

  const runtime = await Deno.readTextFile("worker-runtime.js");

  const unitJs = [
    "// Generated by tools/brouter-wasm/vendor.sh — do not edit by hand.",
    `const WASM_GZ_B64 = ${JSON.stringify(b64)};`,
    `const LOOKUPS_DAT = ${JSON.stringify(lookups)};`,
    `const PROFILES = ${JSON.stringify(profiles)};`,
    `const EMBEDDED_SEGMENTS_GZ_B64 = ${JSON.stringify(embeddedSegments)};`,
    glue,
    runtime,
  ].join("\n\n");

  await Deno.writeTextFile("../../shell/units/brouter/unit.js", unitJs);
  console.log(`Wrote shell/units/brouter/unit.js (${(unitJs.length / 1024).toFixed(1)} KB)`);
'
